#!/usr/bin/env python3
"""Recover initialised data tables from the original PC executable.

The decomp has recovered almost none of the game's .data yet, so tables the
code declares `extern` resolve to zero-filled link stubs. This reads them from
speed.exe (1.3) and writes C++ definitions with native-width fields.

Usage (from repo root):
    python3 -I port/tools/gen_data.py [--exe ~/Games/NFSMW/speed.exe]

Writes port/src/Data/RecoveredData.cpp. Each table is described in TABLES:
a C++ declaration plus per-field readers. Pointers are re-expressed as
references to other recovered symbols or string literals, never raw addresses.
"""

import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe import PE  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "port", "src", "Data", "RecoveredData.cpp")


def c_string(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append(f"\\x{ord(ch):02x}")
    return '"' + "".join(out) + '"'


# Field readers: (size_in_original, fn(pe, va, ctx) -> C++ expression)
def u32():
    return 4, lambda pe, va, ctx: f"0x{pe.u32(va):08X}u"


def i32():
    return 4, lambda pe, va, ctx: str(struct.unpack("<i", pe.read(va, 4))[0])


def char():
    return 1, lambda pe, va, ctx: str(struct.unpack("<b", pe.read(va, 1))[0])


def cstr():
    def read(pe, va, ctx):
        p = pe.u32(va)
        return "nullptr" if p == 0 else f"const_cast<char *>({c_string(pe.cstr(p))})"
    return 4, read


def null_ptr():
    """A pointer the PC build doesn't have (field exists only on other platforms)."""
    return 0, lambda pe, va, ctx: "nullptr"


def ref():
    """Pointer to another recovered table: emitted as &symbol."""
    def read(pe, va, ctx):
        p = pe.u32(va)
        if p == 0:
            return "nullptr"
        if p not in ctx["by_addr"]:
            raise SystemExit(f"pointer {p:#x} at {va:#x} targets a table that isn't in TABLES")
        return "&" + ctx["by_addr"][p]
    return 4, read


def cast(type_, reader):
    size, fn = reader
    return size, lambda pe, va, ctx: f"static_cast<{type_}>({fn(pe, va, ctx)})"


def array(n, reader):
    size, fn = reader
    return size * n, lambda pe, va, ctx: "{" + ", ".join(fn(pe, va + i * size, ctx) for i in range(n)) + "}"


# Each table: symbol, PC address, C++ type, element count (None = scalar),
# original element stride, fields (in declaration order).
TABLES = [
    # --- Frontend/Localization/Localize.cpp (PC InitLocalization @ 0x56B820) ---
    dict(name="LanguageMemoryPoolNumber", addr=0x8F4004, type="int", count=None, stride=4, fields=[i32()]),
    dict(name="FontSizeInfoTable", addr=0x8F4008, type="FontSizeInfo", count=11, stride=8, fields=[u32(), i32()]),
    dict(name="EropeanFontNameInfo", addr=0x8F4060, type="FontNameInfo", count=None, stride=0x6C,
         fields=[array(8, u32()), array(8, u32()), array(8, u32()), i32(), i32(), i32()]),
] + [
    dict(name=f"{lang}LocaleInfo", addr=0x8F40CC + i * 4, type="bPrintfLocaleInfo", count=None, stride=4,
         fields=[char(), char(), char()])
    for i, lang in enumerate(["English", "French", "German", "Italian", "Spanish", "Dutch", "Swedish", "Polish", "Finnish", "Danish"])
] + [
    # --- Frontend/Database/FEDatabase.cpp: controller config attribute keys, [config][analog]
    # (declared Attrib::Key [5][2]; flattened here, same storage) ---
    dict(name="DriveConfigs", addr=0x89F6AC, type="unsigned int", count=10, stride=4, fields=[u32()]),
    dict(name="HudConfigs", addr=0x89F6D4, type="unsigned int", count=10, stride=4, fields=[u32()]),
] + [
    dict(name="LanguageInfoTable", addr=0x8F40F8, type="LanguageInfo", count=10, stride=0x14,
         fields=[cast("eLanguages", i32()), cstr(), cstr(), null_ptr(), ref(), ref()]),
]

PREAMBLE = """// GENERATED by port/tools/gen_data.py from speed.exe 1.3 -- do not edit by hand.
//
// Initialised data the decomp hasn't recovered yet. Values are read from the
// original PC executable; pointers are rebuilt as references to other tables.

#include "Speed/Indep/bWare/Inc/bPrintf.hpp"
#include "Speed/Indep/Src/Frontend/Localization/Localize.hpp"

// Layouts from Speed/Indep/Src/Frontend/Localization/Localize.cpp, which keeps
// these private to that file.
struct FontNameInfo {
    uint32 GlobalFonts[8];
    uint32 InGameFonts[8];
    uint32 FrontendFonts[8];
    int GlobalFontsLoaded;
    int InGameFontsLoaded;
    int FrontendFontsLoaded;
};

struct LanguageInfo {
    eLanguages Language;
    char *Name;
    char *Filename;
    char *FilenameTextOnly; // GameCube only (ARAM); not in the PC table
    FontNameInfo *pFontNameInfo;
    bPrintfLocaleInfo *pbPrintfLocaleInfo;
};

struct FontSizeInfo {
    uint32 Hash;
    int Size;
};
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", default=os.path.expanduser("~/Games/NFSMW/speed.exe"))
    args = ap.parse_args()
    pe = PE(args.exe)

    ctx = {"by_addr": {t["addr"]: t["name"] for t in TABLES}}
    out = [PREAMBLE]
    for t in TABLES:
        def element(base):
            vals, off = [], 0
            for size, fn in t["fields"]:
                vals.append(fn(pe, base + off, ctx))
                off += size
            if off > t["stride"]:
                raise SystemExit(f"{t['name']}: fields span {off:#x} > stride {t['stride']:#x}")
            return vals

        out.append(f"// {t['name']} @ {t['addr']:#x}")
        if t["count"] is None:
            vals = element(t["addr"])
            init = vals[0] if len(vals) == 1 and len(t["fields"]) == 1 else "{" + ", ".join(vals) + "}"
            out.append(f"{t['type']} {t['name']} = {init};\n")
        else:
            out.append(f"{t['type']} {t['name']}[{t['count']}] = {{")
            for i in range(t["count"]):
                out.append("    {" + ", ".join(element(t["addr"] + i * t["stride"])) + "},")
            out.append("};\n")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(TABLES)} tables)")


if __name__ == "__main__":
    main()
