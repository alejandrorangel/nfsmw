// Snapshot of keyboard and gamepad state for the game's native input device.
// Written from Cocoa / GameController, read by the game thread.
#pragma once

enum PortKey {
    PORT_KEY_ESCAPE, PORT_KEY_ENTER, PORT_KEY_SPACE, PORT_KEY_BACKSPACE, PORT_KEY_TAB,
    PORT_KEY_UP, PORT_KEY_DOWN, PORT_KEY_LEFT, PORT_KEY_RIGHT,
    PORT_KEY_PAGEUP, PORT_KEY_PAGEDOWN, PORT_KEY_INSERT, PORT_KEY_DELETE, PORT_KEY_HOME, PORT_KEY_END,
    PORT_KEY_LSHIFT, PORT_KEY_RSHIFT, PORT_KEY_LCONTROL, PORT_KEY_RCONTROL, PORT_KEY_LALT, PORT_KEY_RALT,
    PORT_KEY_MINUS, PORT_KEY_EQUALS, PORT_KEY_LBRACKET, PORT_KEY_RBRACKET, PORT_KEY_BACKSLASH,
    PORT_KEY_SEMICOLON, PORT_KEY_APOSTROPHE, PORT_KEY_COMMA, PORT_KEY_PERIOD, PORT_KEY_SLASH, PORT_KEY_GRAVE,
    PORT_KEY_F1, PORT_KEY_F2, PORT_KEY_F3, PORT_KEY_F4, PORT_KEY_F5, PORT_KEY_F6,
    PORT_KEY_F7, PORT_KEY_F8, PORT_KEY_F9, PORT_KEY_F10, PORT_KEY_F11, PORT_KEY_F12,
    PORT_KEY_NUMPAD0, PORT_KEY_NUMPAD1, PORT_KEY_NUMPAD2, PORT_KEY_NUMPAD3, PORT_KEY_NUMPAD4,
    PORT_KEY_NUMPAD5, PORT_KEY_NUMPAD6, PORT_KEY_NUMPAD7, PORT_KEY_NUMPAD8, PORT_KEY_NUMPAD9,
    PORT_KEY_NUMPADENTER, PORT_KEY_ADD, PORT_KEY_SUBTRACT, PORT_KEY_MULTIPLY, PORT_KEY_DIVIDE, PORT_KEY_DECIMAL,
    PORT_KEY_A, // A..Z follow contiguously
    PORT_KEY_0 = PORT_KEY_A + 26, // 0..9 follow contiguously
    PORT_KEY_COUNT = PORT_KEY_0 + 10,
};

enum PortPad {
    PORT_PAD_A, PORT_PAD_B, PORT_PAD_X, PORT_PAD_Y,
    PORT_PAD_LSHOULDER, PORT_PAD_RSHOULDER, PORT_PAD_LTRIGGER, PORT_PAD_RTRIGGER,
    PORT_PAD_START, PORT_PAD_BACK, PORT_PAD_LSTICK, PORT_PAD_RSTICK,
    PORT_PAD_DUP, PORT_PAD_DDOWN, PORT_PAD_DLEFT, PORT_PAD_DRIGHT,
    PORT_PAD_LX, PORT_PAD_LY, PORT_PAD_RX, PORT_PAD_RY, // -1..1, +y = up
    PORT_PAD_COUNT,
};

struct PortInputState {
    float keys[PORT_KEY_COUNT]; // 0 or 1
    float pad[PORT_PAD_COUNT];
    bool pad_connected;
};

// Fills a consistent snapshot of the current state (callable from any thread).
void PortInputGetState(PortInputState *out);
